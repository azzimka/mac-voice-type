import Cocoa
import Carbon

/// Надежный сервис прямого ввода распознанного текста в активное приложение.
///
/// Преимущества:
/// 1. Прямой ввод через CoreGraphics Unicode Key Events (postToPid / cghidEventTap).
/// 2. Буфер обмена пользователя (NSPasteboard.general) НЕ ЗАТРАГИВАЕТСЯ:
///    - Скопированные пользователем данные сохраняются в первозданном виде.
///    - Сторонние приложения (Reverso, Alfred, Raycast) не получают ложных событий
///      изменения буфера и не всплывают на экране.
/// 3. Пакетная передача (до 20 Unicode символов в одном событии) обеспечивает
///    мгновенную вставку текста любой длины без задержек.
final class TextInjector {
    static let shared = TextInjector()
    private init() {}

    static func checkAccessibilityPermission(prompt: Bool = false) -> Bool {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: prompt]
        return AXIsProcessTrustedWithOptions(options as CFDictionary)
    }

    func insertText(_ text: String, targetApp: NSRunningApplication? = nil, mode: DictationMode = .dictation) {
        guard !text.isEmpty else {
            print("[Froggy] TextInjector: text is empty, skipping")
            return
        }

        DispatchQueue.main.async { [self] in
            // Режим разработчика ИЛИ любой многострочный текст/код со скобками
            // ВСЕГДА вставляется через атомарный Paste (⌘V), чтобы редакторы кода
            // (VS Code, Xcode, JetBrains) не вызывали авто-отступы (staircase indent)
            // и авто-закрытие дублирующих скобок.
            let containsNewlines = text.contains("\n")
            let hasBrackets = text.contains("{") || text.contains("[") || text.contains("(")
            let shouldUsePaste = (mode == .developer) || containsNewlines || (hasBrackets && text.count > 15)

            if shouldUsePaste {
                self.performPasteInsert(text, targetApp: targetApp)
            } else {
                self.performDirectInsert(text, targetApp: targetApp)
            }
        }
    }

    private func performPasteInsert(_ text: String, targetApp: NSRunningApplication?) {
        let app = (targetApp != nil && !(targetApp?.isTerminated ?? true))
            ? targetApp
            : NSWorkspace.shared.frontmostApplication

        guard let target = app else {
            print("[Froggy] TextInjector: no target application for paste, fallback to HID typing")
            typeViaHID(text)
            return
        }

        if target.processIdentifier != NSWorkspace.shared.frontmostApplication?.processIdentifier {
            if #available(macOS 14.0, *) {
                target.activate()
            } else {
                target.activate(options: [.activateIgnoringOtherApps])
            }
            usleep(35_000)
        }

        let pasteboard = NSPasteboard.general

        // 1. Сохраняем текущие элементы буфера обмена (все типы и данные: текст, файлы, картинки)
        var savedItems: [[NSPasteboard.PasteboardType: Data]] = []
        if let items = pasteboard.pasteboardItems {
            for item in items {
                var dict = [NSPasteboard.PasteboardType: Data]()
                for type in item.types {
                    if let data = item.data(forType: type) {
                        dict[type] = data
                    }
                }
                if !dict.isEmpty {
                    savedItems.append(dict)
                }
            }
        }

        // 2. Помещаем код в буфер с маркерами Transient / AutoGenerated
        // Менеджеры буфера (Raycast, Alfred, Paste, Maccy) игнорируют транзитные вставки
        pasteboard.clearContents()
        let newItem = NSPasteboardItem()
        newItem.setString(text, forType: .string)
        newItem.setString("1", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        newItem.setString("1", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([newItem])

        let expectedChangeCount = pasteboard.changeCount

        print("[Froggy] TextInjector: atomic pasting \(text.count) chars (⌘V) into \(target.localizedName ?? "app") (PID: \(target.processIdentifier))")

        // 3. Симулируем ⌘V (Command + V)
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKeyCode = CGKeyCode(kVK_ANSI_V) // 9
        let cmdKeyCode = CGKeyCode(kVK_Command) // 55

        guard let cmdDown = CGEvent(keyboardEventSource: source, virtualKey: cmdKeyCode, keyDown: true),
              let vDown = CGEvent(keyboardEventSource: source, virtualKey: vKeyCode, keyDown: true),
              let vUp = CGEvent(keyboardEventSource: source, virtualKey: vKeyCode, keyDown: false),
              let cmdUp = CGEvent(keyboardEventSource: source, virtualKey: cmdKeyCode, keyDown: false) else {
            print("[Froggy] TextInjector: failed to create paste events, falling back to direct typing")
            performDirectInsert(text, targetApp: target)
            return
        }

        vDown.flags = .maskCommand
        vUp.flags = .maskCommand

        cmdDown.post(tap: .cghidEventTap)
        vDown.post(tap: .cghidEventTap)
        vUp.post(tap: .cghidEventTap)
        cmdUp.post(tap: .cghidEventTap)

        // 4. Бесшовно восстанавливаем исходный буфер обмена через 250 мс
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.25) {
            guard pasteboard.changeCount == expectedChangeCount else {
                print("[Froggy] TextInjector: user copied new data during paste, preserving it")
                return
            }

            pasteboard.clearContents()
            if !savedItems.isEmpty {
                var restored: [NSPasteboardItem] = []
                for dict in savedItems {
                    let rItem = NSPasteboardItem()
                    for (type, data) in dict {
                        rItem.setData(data, forType: type)
                    }
                    restored.append(rItem)
                }
                pasteboard.writeObjects(restored)
                print("[Froggy] TextInjector: restored \(savedItems.count) previous clipboard items")
            }
        }
    }

    private func performDirectInsert(_ text: String, targetApp: NSRunningApplication?) {
        // Определяем целевое приложение (переданное или текущее активное)
        let app = (targetApp != nil && !(targetApp?.isTerminated ?? true))
            ? targetApp
            : NSWorkspace.shared.frontmostApplication

        guard let target = app else {
            print("[Froggy] TextInjector: no target application, fallback to HID event tap")
            typeViaHID(text)
            return
        }

        // Если фокус временно сместился, мягко возвращаем фокус целевому приложению
        if target.processIdentifier != NSWorkspace.shared.frontmostApplication?.processIdentifier {
            if #available(macOS 14.0, *) {
                target.activate()
            } else {
                target.activate(options: [.activateIgnoringOtherApps])
            }
            usleep(25_000) // 25 мс для активации окна
        }

        let pid = target.processIdentifier
        let source = CGEventSource(stateID: .combinedSessionState)
        let chars = Array(text)
        let chunkSize = 20

        print("[Froggy] TextInjector: directly typing \(chars.count) chars into \(target.localizedName ?? "app") (PID: \(pid)) without touching clipboard")

        for i in stride(from: 0, to: chars.count, by: chunkSize) {
            let end = min(i + chunkSize, chars.count)
            let chunkString = String(chars[i..<end])
            var utf16 = Array(chunkString.utf16)

            guard let keyDown = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: true),
                  let keyUp = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: false) else {
                continue
            }

            keyDown.keyboardSetUnicodeString(stringLength: utf16.count, unicodeString: &utf16)
            keyUp.keyboardSetUnicodeString(stringLength: utf16.count, unicodeString: &utf16)

            keyDown.postToPid(pid)
            keyUp.postToPid(pid)
            usleep(1500) // 1.5 мс между пакетами для надежной обработки полем ввода
        }

        print("[Froggy] TextInjector: direct insertion completed successfully")
    }

    private func typeViaHID(_ text: String) {
        let source = CGEventSource(stateID: .combinedSessionState)
        let chars = Array(text)
        let chunkSize = 20

        for i in stride(from: 0, to: chars.count, by: chunkSize) {
            let end = min(i + chunkSize, chars.count)
            let chunkString = String(chars[i..<end])
            var utf16 = Array(chunkString.utf16)

            guard let keyDown = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: true),
                  let keyUp = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: false) else {
                continue
            }

            keyDown.keyboardSetUnicodeString(stringLength: utf16.count, unicodeString: &utf16)
            keyUp.keyboardSetUnicodeString(stringLength: utf16.count, unicodeString: &utf16)

            keyDown.post(tap: .cghidEventTap)
            keyUp.post(tap: .cghidEventTap)
            usleep(1500)
        }
    }
}
